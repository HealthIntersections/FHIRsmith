function render(ips) {
  var composition = ips.entry?.find(e => e.resource?.resourceType === "Composition")?.resource;
  if (!composition) {
    return "<p>This document has no Composition resource, so there is nothing to show.</p>";
  }
  var html = "<h1>"+escapeText(composition.title || "Health Document")+"</h1>\r\n"+
    "<p>This document was created using the "+
    "<a href=\"https://www.healthintersections.com.au/passport.html\">Patient Health Document Generator</a> "+
    "provided by <img src=\""+(window.PATIENT_EDITOR ? window.PATIENT_EDITOR.assets : "/assets")+"/images/health-intersections-inline.png\" height=\"30\" width=\"300\">"+
    "</p>";

  // Documents built elsewhere often carry no narrative on the Patient itself, so
  // fall back to the handful of demographics we would have shown anyway.
  var subject = findResource(ips, composition.subject);
  if (subject) {
    html += narrativeOf(subject) || renderPatientSummary(subject);
  }

  var compositionNarrative = narrativeOf(composition);
  if (compositionNarrative) {
    html += '<h2>Composition</h2>\r\n';
    html += compositionNarrative;
  }

  var sections = composition.section || [];
  for (var i = 0; i < sections.length; i++) {
    var sectionNarrative = narrativeOf(sections[i]);
    if (sectionNarrative) {
      if (sections[i].title) {
        html += '<h2>'+escapeText(sections[i].title)+'</h2>\r\n';
      }
      html += sectionNarrative;
    }
  }
  return html;
}

// Minimal stand-in when a Patient resource has no narrative of its own
function renderPatientSummary(patient) {
  var name = patient.name?.[0];
  var text = name?.text || [(name?.given || []).join(' '), name?.family].filter(part => part).join(' ');
  var details = [];
  if (patient.gender) {
    details.push(patient.gender);
  }
  if (patient.birthDate) {
    details.push('born ' + patient.birthDate);
  }
  var html = '<p><b>' + escapeText(text || 'Patient') + '</b></p>';
  if (details.length) {
    html += '<p>' + escapeText(details.join(', ')) + '</p>';
  }
  return html;
}
