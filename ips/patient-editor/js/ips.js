const root = "http://healthintersections.com.au/ips";
var rcount = 0;
var patDesc = "";

async function genIPS(form) {
  var now = new Date().toISOString();

  var bnd = makeBundle(now);
  var comp = makeComposition(form, now);
  addToBundle(bnd, comp);
  addToBundle(bnd, makePatient(form));
  addToBundle(bnd, makeMyStory(bnd, comp, now, form));
  makeAllergyResources(bnd, comp, now, form);
  makeProblemResources(bnd, comp, now, form);
  makeMedicationResources(bnd, comp, now, form);
  makeHistoryResources(bnd, comp, now, form);
  makeFunctionalStatusResources(bnd, comp, now, form);
  makeCareTeamResources(bnd, comp, now, form);
  makePregnancySection(bnd, comp, now, form);
  makeBodyPartSurvey(bnd, comp, now, form);
  makeReproductiveSection(bnd, comp, now, form);
  await makeCareDirectiveResources(bnd, comp, now, form);

  return bnd;
}

function makeBundle(now) {
  const uuid = generateUUID();
  let res = {
    resourceType: "Bundle",
    id: uuid,
    type: "document",
    timestamp: now,
    identifier: { "system": "urn:ietf:rfc:3986", "value": "urn:uuid:" + uuid }
  };
  return res;
}

function addToBundle(bnd, res) {
  if (res) {
    (bnd.entry ??= []).push({
      fullUrl: buildUrl(root, res.resourceType, res.id),
      resource: res
    });
  }
}

function makeComposition(form, now) {
  let res = {
    resourceType: "Composition",
    id: "cmp1",
    text: {
      status: "generated",
      div : "<div xmlns=\"http://www.w3.org/1999/xhtml\">Patient Document generated by Health Intersections Patient Health Document Generator</div>"
    },
    title: "Patient Document (IPS)",
    status: "final",
    type: {
      coding: [{
        system: "http://loinc.org",
        code: "60591-5"
      }]
    },
    subject: {
      reference: "Patient/pat1"
    },
    date: now.split('T')[0]
  }
  if (iss(form.get("author"))) {
    res.author = [{ display: form.get("author") }];
  } else {
    res.author = [{ reference: "Patient/pat1" }];
  }
  return res;
}

function makePatient(form) {
  var ag, sg, cg, dg, tg, sp, cdp, dp, tp, sv, cdv, dv, tv;
  var ext = false;
  const div = xhtml.div();

  if (iss(form.get('gender'))) {
    switch (form.get('gender')) {
      case "f":
        sg = 'http://snomed.info/sct';
        cg = '446141000124107';
        dg = 'Female gender identity';
        tg = 'Female';
        ag = 'female';
        break;
      case 'm':
        sg = 'http://snomed.info/sct';
        cg = '446151000124109';
        dg = 'Male gender identity';
        tg = 'Male';
        ag = 'male';
        break;
      case "n":
        sg = 'http://snomed.info/sct';
        cg = '33791000087105';
        dg = 'Non-binary gender identity';
        tg = 'Non-binary';
        ag = 'other';
        break;
      case "u":
        sg = 'http://terminology.hl7.org/CodeSystem/data-absent-reason';
        cg = 'asked-declined';
        dg = 'Asked But Declined';
        tg = '';
        break;
      default:
        throw new Error('Unknown value for gender: "' + form.get('gender')+"'");
    }
  }
  if (iss(form.get('pronouns'))) {
    switch (form.get('pronouns')) {
      case 'f':
        sp = 'http://loinc.org';
        cdp = 'LA29519-8';
        dp = 'she/her/her/hers/herself';
        tp = 'she/her';
        break;
      case 'm':
        sp = 'http://loinc.org';
        cdp = 'LA29518-0';
        dp = 'he/him/his/his/himself';
        tp = 'he/him';
        break;
      case 'o':
        sp = 'http://loinc.org';
        cdp = 'LA29520-6';
        dp = 'they/them/their/theirs/themselves';
        tp = 'they/them';
        break;
      default:
        throw new Error('Unknown value for pronouns: ' + form.get('pronouns'));
    }
  }

  if (iss(form.get('sexchar'))) {
    switch (form.get('sexchar')) {
      case 'n':
        sv = 'http://www.abs.gov.au/ausstats/XXXX';
        cdv = '2';
        dv = 'No';
        tv = 'Typical Sex Characteristics';
        break;
      case 'y':
        sv = 'http://www.abs.gov.au/ausstats/XXXX';
        cdv = '1';
        dv = 'Yes';
        tv = 'Atypical Sex Characteristics';
        break;
      case 'u':
        sv = 'http://www.abs.gov.au/ausstats/XXXX';
        cdv = '3';
        dv = 'Don\'t know';
        tv = 'Unsure about sex characteristics';
        break;
      default:
        throw new Error('Unknown value for typical sex characteristics: ' + form.get('sexchar'));
    }
  }

  let res = {
    resourceType: "Patient",
    id: "pat1",
  };
  if (iss(form.get('name'))) {
    res.name = [{ text: form.get('name'), "_family" : { "extension" : [{ "url" : "http://hl7.org/fhir/StructureDefinition/data-absent-reason", "valueCode" : "unsupported" }]}} ];
    div.tx('Patient: ' + form.get('name'));
    patDesc += form.get('name');
  }
  if (ag) {
    res.gender = ag;
  }
  if (iss(form.get('dob'))) {
    res.birthDate = parseAndFormatDate(form.get('dob'));
    div.sep(', ');
    div.tx('born ' + form.get('dob'));
    patDesc += ', ' + form.get('dob');
  }

  if (iss(tg) || iss(form.get("gender-other"))) {
    var vg = iss(tg) ? tg : form.get("gender-other");
    div.sep(', ');
    div.tx('(' + vg + ' gender');
    if (iss(tp)) {
      div.tx(', ' + tp);
    }
    div.tx(')');
    ext = true;
    if (iss(tg)) {
      (res.extension ??= []).push({
        url: "http://hl7.org/fhir/StructureDefinition/individual-genderIdentity",
        extension: [{
          url: "value",
          valueCodeableConcept: { coding: [{ system: sg, code: cg, display: dg }] }
        }]
      });
    } else {
      (res.extension ??= []).push({
        url: "http://hl7.org/fhir/StructureDefinition/individual-genderIdentity",
        extension: [{
          url: "value",
          valueCodeableConcept: { text : vg }
        }]
      });      
    }
  }

  if (iss(tp) || iss(form.get("pronouns-other"))) {
    var vp = iss(tp) ? tp : form.get("pronouns-other");
    if (tg == '') {
      div.sep(', ');
      div.tx(' (' + vp + ')');
    }
    ext = true;
    if (iss(tp)) {
      (res.extension ??= []).push({
        url: "http://hl7.org/fhir/StructureDefinition/individual-pronouns",
        extension: [{
          url: "value",
          valueCodeableConcept: { coding: [{ system: sp, code: cdp, display: dp }] }
        }]
    });
    } else {
      (res.extension ??= []).push({
        url: "http://hl7.org/fhir/StructureDefinition/individual-pronouns",
        extension: [{
          url: "value",
          valueCodeableConcept: { text: form.get("pronouns-other") }
        }]
      });
    }
  }
  if (iss(tv)) {
    var vsv = form.get('sex-variance');
    div.tx(' (' + tv + (vsv ? ": "+vsv : "")+ ')');
    ext = true;
    (res.extension ??= []).push({
      url: "http://healthintersections.com.au/fhir/StructureDefinition/sex-characteristic-variation",
      valueCodeableConcept: { coding: [{ system: sv, code: cdv, display: dv }] }
    });
    if (iss(vsv)) {
      (res.extension ??= []).push({
        url: "http://healthintersections.com.au/fhir/StructureDefinition/sex-characteristic-variation-details",
        valueString: vsv
      });
    }
  }

  if (iss(form.get('id'))) {
    res.identifier = [{ type: { coding: [{ system: 'http://terminology.hl7.org/CodeSystem/v2-0203', code: 'NIIP', display: 'National Insurance Payor Identifier (Payor)' }] },"_system" : {"extension" : [{"url" : "http://hl7.org/fhir/StructureDefinition/data-absent-reason","valueCode" : "unsupported"}]}, value: form.get('id') }];
    div.tx(". ");
    div.tx('National ID ' + form.get('id'));
    patDesc += ', National ID ' + form.get('id');
    if (iss(form.get('country'))) {
      div.tx(' for ' + form.get('country'));
    }
  }
  if (iss(form.get('country'))) {
    res.address = [{ country: form.get('country') }];
  }
  div.br();

  if (iss(form.get('culture'))) {
    (res.extension ??= []).push({
      url: 'http://healthintersections.com.au/fhir/StructureDefinition/patient-cultural-background',
      valueString: form.get('culture')
    });
    ext = true;
    div.tx('Cultural background: ' + form.get('culture'));
    div.br();
  }

  if (iss(form.get('community'))) {
    (res.extension ??= []).push({
      url: 'http://healthintersections.com.au/fhir/playground/StructureDefinition/community',
      valueString: form.get('community')
    });
  }

  if (iss(form.get('email')) || iss(form.get('mobile')) || iss(form.get('phone'))) {
    div.tx('Contacts: ');
    var hc = false;
    if (iss(form.get('email'))) {
      hc = true;
      (res.telecom ??= []).push({ system: "email", value: form.get('email') });
      div.tx('email: ');
      div.ah('mailto:' + form.get('email')).tx(form.get('email'));
    }
    if (iss(form.get('mobile'))) {
      if (hc) {
        div.sep(', ');
      }
      (res.telecom ??= []).push({ system: "phone", use: "mobile", value: form.get('mobile') });
      hc = true;
      div.tx('mobile: ');
      div.ah('tel:' + form.get('mobile')).tx(form.get('mobile'));
    }
    if (iss(form.get('phone'))) {
      if (hc) {
        div.tx(', ');
      }
      (res.telecom ??= []).push({ system: "phone", value: form.get('phone') });
      div.tx('phone: ');
      div.ah('tel:' + form.get('phone')).tx(form.get('phone'));
    }
  }

  if (iss(form.get('nok'))) {
    div.br();
    div.tx('Next of Kin: ' + form.get('nok'));
    var nok = { name: { text: form.get('nok') } };
    (res.contact ??= []).push(nok);

    if (iss(form.get('nokemail')) || iss(form.get('nokmobile')) || iss(form.get('nokphone'))) {
      div.tx(', contacts: ');
      var hc = false;
      if (iss(form.get('nokemail'))) {
        (nok.telecom ??= []).push({ system: "email", value: form.get('nokemail') });
        hc = true;
        div.tx('email: ');
        div.ah('mailto:' + form.get('nokemail')).tx(form.get('nokemail'));
      }
      if (iss(form.get('nokmobile'))) {
        if (hc) {
          div.tx(', ');
        }
        (nok.telecom ??= []).push({ system: "phone", use: "mobile", value: form.get('nokmobile') });
        hc = true;
        div.tx('mobile: ');
        div.ah('tel:' + form.get('nokmobile')).tx(form.get('nokmobile'));
      }
      if (iss(form.get('nokphone'))) {
        if (hc) {
          div.tx(', ');
        }
        (nok.telecom ??= []).push({ system: "phone", value: form.get('nokphone') });
        div.tx('phone: ');
        div.ah('tel:' + form.get('nokphone')).tx(form.get('nokphone'));
      }
    }
  }

  if (iss(form.get('language'))) {
    var s = form.get('language').toLowerCase();
    res.communication = [{ preferred: true, language: { text: form.get('language') } }];
    if ((s != 'en') && (s != 'english')) {
      if (iss(form.get('english'))) {
        res.communication.push({ language: { text: 'english' } });
      }
    }
  } 
  if (iss(form.get('religion'))) {
    var religion = null;
    switch (form.get('religion')) {
    case "n": 
      religion = 'Not important';
      break;
    case "x":
      religion = 'Christian';
      break;
    case "m": 
      religion = 'Muslim';
      break;
    case "h": 
      religion = 'Hindu';
      break;
    case "b": 
      religion = 'Buddhist';
      break;
    case "o": 
      religion = 'Other';
      break;
    }
    var cc = { "text" : religion };
    if (form.get('religion-code')) {
      const concept = $('#religion-code').data('selected-concept');
      if (concept) {
        (cc.coding ??= []).push({ system : concept.system, code: concept.code, display: form.get('religion-code')});
      }
    }
    (res.extension ??= []).push({
      url: 'http://hl7.org/fhir/StructureDefinition/patient-religion',
      valueCodeableConcept: cc
    });
  }

  res.text = { status: ext ? 'extensions' : 'generated', div: div.done().outerHTML };
  return res;
}

function makeMyStory(bnd, comp, now, form) {
  var sect = addSection(comp, 'Patient Story', 'http://loinc.org', '81338-6');
  var src = form.get('story').trim();

  (sect.extension ??= []).push({
    url: 'http://healthintersections.com.au/fhir/StructureDefinition/patient-story',
    valueString: src
  });

  if (!iss(src)) {
    src = "No Patient Story provided";
  } 

  var goals = false;
  for (i = 1; i <= goalCount; i++) {
    var gs = form.get('care-goal-'+i);
    if (iss(gs)) {
      addToBundle(bnd, makeGoal(form, sect, now, gs, form.get('care-goal-state-'+i)));
      if (iss(form.get('care-goal-state-'+i))) {
        gs += " (in progress)"
      }
      if (!goals) {
        src += "\r\n\r\n**Patient's Goals**\r\n\r\n";
        goals = true;
      }
      src += "* "+gs+"\r\n";
    }
  }
  const reader = new commonmark.Parser();
  const writer = new commonmark.HtmlRenderer();
  const parsed = reader.parse(src);
  const html = writer.render(parsed);
  sect.text = { status: 'generated', div: '<div xmlns=\"http://www.w3.org/1999/xhtml\">'+html+"</div>" };
}

function makeGoal(form, sect, now, gs, gss) {
  var div = xhtml.div();
  var res = {
    resourceType: "Goal",
    id: "gl" + (++rcount),
    lifecycleStatus: 'active',
    subject: { reference: "Patient/pat1" },
    statusDate: now.split('T')[0],
    description: { text : gs }
  };
  (sect.entry ??= []).push({ reference: 'Goal/' + res.id });
  div.p().tx('Goal for ' + patDesc);
  var p = div.p();
  p.tx(gs);
  if (iss(gss)) {
    p.tx(" (in progress)");
    res.achievementStatus = { coding: [{ system: 'http://terminology.hl7.org/CodeSystem/goal-achievement', code: 'in-progress', display: 'In Progress'}]}
  } else {
    res.achievementStatus = { coding: [{ system: 'http://terminology.hl7.org/CodeSystem/goal-achievement', code: 'not-achieved', display: 'Not Achieved'}]}
  }
  res.text = { status: 'generated', div: div.done().outerHTML };
  return res;
}

function makeAllergyResources(bnd, comp, now, form) {
  var sect = addSection(comp, 'Allergies and adverse reactions', 'http://loinc.org', '48765-2');
  const sdiv = xhtml.div();
  var ul = sdiv.ul();
  var issues = false;
  for (i = 1; i <= allergyCount; i++) {
    if (iss(form.get('ai'+i))) {
      issues = true;
      var res = {
        resourceType: "AllergyIntolerance",
        id: "ai" + (++rcount),
        clinicalStatus: { coding: [{ system: 'http://terminology.hl7.org/CodeSystem/allergyintolerance-clinical', code: 'active', display: 'Active' }] },
        patient: { reference: "Patient/pat1" },
        recordedDate: now
      };
      (sect.entry ??= []).push({ reference: 'AllergyIntolerance/' + res.id });
      var text = form.get('ai'+i).trim();
      const concept = $('#ai'+i).data('selected-concept');
      if (concept) {
        res.code = { text : text, coding: [{ system : concept.system, code: concept.code}]};
      } else {
        res.code = { text : text};
      }
      if (iss(form.get('aiRxn'+i))) {
        var manifestation = makeManifestation(form.get('aiRxn'+i));
        res.reaction = [{
          manifestation: [manifestation]
        }];
        text += ": " + manifestation.text;
      }
      ul.li().tx(text);
      var div = xhtml.div();
      div.p().tx('Allergy for ' + patDesc);
      div.p().tx(text);
      res.text = { status: 'generated', div: div.done().outerHTML };
      addToBundle(bnd, res);
    }
  }
  if (issues) {
    sect.text = { status: 'generated', div: sdiv.done().outerHTML };
  } else {
    sect.text = { status: 'generated', div: '<div  xmlns=\"http://www.w3.org/1999/xhtml\">No Allergies Documented</div>' };
    sect.emptyReason = { coding: [{system: "http://terminology.hl7.org/CodeSystem/list-empty-reason", code: "unavailable"}]};
  }
}

