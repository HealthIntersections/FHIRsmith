async function makeDocRef(sect, ul) {
  const fileInput = document.querySelector('#myfile');
  if (!fileInput || !fileInput.files[0]) {
    return null;
  }

  const file = fileInput.files[0];
  // Convert file reading to Promise
  const b64 = await new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const result = reader.result
          .replace('data:', '')
          .replace(/^.+,/, '');  // Strip the data:... prefix
      resolve(result);
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });

  var li = ul.li();
  var div = xhtml.div();
  var res = {
    resourceType: 'DocumentReference',
    status: 'current',
    id: 'dr' + (++rcount),
    patient: { reference: 'Patient/pat1' },
    type: { coding: [{ system: 'http://loinc.org', code: '75320-2', display: 'Advance directive' }] },
    content: [{ data: b64, mimeType: "application/pdf" }]
  };

  li.tx('Advance Care Directive');
  div.p().tx('Advance Care Directive for ' + patDesc);
  
  (sect.entry ??= []).push({ reference: 'DocumentReference/' + res.id });
  res.text = { status: 'generated', div: div.done().outerHTML };
  return res;
}

