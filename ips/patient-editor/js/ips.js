function makeProblemResources(bnd, comp, now, form) {
  var sect = addSection(comp, 'Health Issues', 'http://loinc.org', '11450-4');
  const sdiv = xhtml.div();
  var ul = sdiv.ul();
  var issues = false;
  for (i = 1; i <= issueCount; i++) {
    if (iss(form.get('issue'+i))) {
      issues = true;
      var res = {
        resourceType: "Condition",
        id: "cnd" + (++rcount),
        category : [{ coding: [{ system: 'http://terminology.hl7.org/CodeSystem/condition-category', code: 'problem-list-item', display: 'Problem List Item' }] }],
        clinicalStatus: { coding: [{ system: 'http://terminology.hl7.org/CodeSystem/condition-clinical', code: 'active', display: 'Active' }] },
        subject: { reference: "Patient/pat1" },
        recordedDate: now
      };
      (sect.entry ??= []).push({ reference: 'Condition/' + res.id });
      var text = form.get('issue'+i).trim();
      const concept = $('#issue'+i).data('selected-concept');
      if (concept) {
        res.code = { text : text, coding: [{ system : concept.system, code: concept.code}]};
      } else {
        res.code = { text : text};
      }
      if (iss(form.get('issueLevel'+i))) {
        res.severity = makeSeverity(form.get('issueLevel'+i));
        text += " ("+res.severity.text+")";
      }
      ul.li().tx(text);
      var div = xhtml.div();
      div.p().tx('Health Issue for ' + patDesc);
      div.p().tx(text);
      res.text = { status: 'generated', div: div.done().outerHTML };
      addToBundle(bnd, res);
    }
  }
  if (issues) {
    sect.text = { status: 'generated', div: sdiv.done().outerHTML };
  } else {
    sect.text = { status: 'generated', div: '<div  xmlns=\"http://www.w3.org/1999/xhtml\">No Issues Documented</div>' };
    sect.emptyReason = { coding: [{system: "http://terminology.hl7.org/CodeSystem/list-empty-reason", code: "unavailable"}]};
  }
}

function makeSeverity(code) {
  switch (code) {
    case "m":
      return { coding: [{ system: 'http://snomed.info/sct', code:'24484000', display: 'Severe'}], text : 'Major Life Challenge'};
    case "c":
      return { coding: [{ system: 'http://snomed.info/sct', code:'6736007', display: 'Moderate severity'}], text : 'Troublesome'};
    case "b":
      return { coding: [{ system: 'http://snomed.info/sct', code:'255604002', display: 'Mild'}], text : 'Background but managed'};
    default:
      return null;
  }
}

